export const ALL_PROVINCES = Object.keys(PROVINCE_CITY_DATA)

export function getProvinceSuggestions(query: string = ''): string[] {
  const q = query.trim().toLowerCase().replace(/[^a-z0-9]/g, '')
  if (!q) return ALL_PROVINCES

  return ALL_PROVINCES.filter(prov => {
    const clean = prov.toLowerCase().replace(/[^a-z0-9]/g, '')
    return clean.includes(q) || prov.toLowerCase().includes(query.trim().toLowerCase())
  })
}

export function getCitySuggestions(province: string = '', query: string = ''): string[] {
  const trimmedProvince = province.trim()
  const q = query.trim().toLowerCase().replace(/[^a-z0-9]/g, '')

  let availableCities: string[] = []

  // Check matching province
  if (trimmedProvince) {
    const provKey = ALL_PROVINCES.find(
      p =>
        p.toLowerCase() === trimmedProvince.toLowerCase() ||
        p.toLowerCase().replace(/[^a-z0-9]/g, '') ===
          trimmedProvince.toLowerCase().replace(/[^a-z0-9]/g, '')
    )

    if (provKey && PROVINCE_CITY_DATA[provKey]) {
      availableCities = PROVINCE_CITY_DATA[provKey]
    }
  }

  // If no province selected or no direct match, pool all cities
  if (availableCities.length === 0 && !trimmedProvince) {
    availableCities = Array.from(
      new Set(Object.values(PROVINCE_CITY_DATA).flat())
    ).sort()
  }

  if (!q) return availableCities

  return availableCities.filter(city => {
    const clean = city.toLowerCase().replace(/[^a-z0-9]/g, '')
    return clean.includes(q) || city.toLowerCase().includes(query.trim().toLowerCase())
  })
}

export function findProvinceByCity(city: string = ''): string | null {
  const cleanCity = city.trim().toLowerCase().replace(/[^a-z0-9]/g, '')
  if (!cleanCity) return null

  for (const [prov, cities] of Object.entries(PROVINCE_CITY_DATA)) {
    const match = cities.some(
      c =>
        c.toLowerCase().replace(/[^a-z0-9]/g, '') === cleanCity ||
        c.toLowerCase().replace(/^(kota|kab|adm)\.?\s*/g, '') ===
          city.toLowerCase().replace(/^(kota|kab|adm)\.?\s*/g, '')
    )
    if (match) return prov
  }

  return null
}

